-- Para cambiar el esquema se agrega un V3, V4...; nunca se edita uno ya aplicado.

CREATE TABLE productos (
    id              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR2(40)  NOT NULL,
    nombre          VARCHAR2(120) NOT NULL,
    descripcion     VARCHAR2(500),
    precio          NUMBER(12)    NOT NULL,
    stock           NUMBER(10)    NOT NULL,
    version         NUMBER(10)    DEFAULT 0 NOT NULL,
    creado_en       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uk_productos_sku    UNIQUE (sku),
    CONSTRAINT ck_productos_precio CHECK (precio >= 0),
    CONSTRAINT ck_productos_stock  CHECK (stock >= 0)   -- el stock nunca puede quedar negativo
);

-- Una reserva por pedido: hace idempotente el descuento de stock
-- (si orders reintenta, no se descuenta dos veces).
CREATE TABLE reservas_stock (
    pedido_id   NUMBER(19)   PRIMARY KEY,
    estado      VARCHAR2(20) NOT NULL,
    creada_en   TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_reservas_estado CHECK (estado IN ('RESERVADA', 'LIBERADA'))
);

CREATE TABLE reserva_items (
    pedido_id    NUMBER(19) NOT NULL,
    producto_id  NUMBER(19) NOT NULL,
    cantidad     NUMBER(10) NOT NULL,
    CONSTRAINT pk_reserva_items PRIMARY KEY (pedido_id, producto_id),
    CONSTRAINT fk_reserva_items_reserva FOREIGN KEY (pedido_id) REFERENCES reservas_stock (pedido_id)
);
