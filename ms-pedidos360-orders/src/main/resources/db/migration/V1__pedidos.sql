-- "pedidos" y no "orders": ORDER es palabra reservada en SQL.
CREATE TABLE pedidos (
    id              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nombre  VARCHAR2(120) NOT NULL,
    cliente_email   VARCHAR2(200) NOT NULL,
    estado          VARCHAR2(20)  NOT NULL,
    total           NUMBER(12)    NOT NULL,
    version         NUMBER(10)    DEFAULT 0 NOT NULL,
    creado_en       TIMESTAMP     NOT NULL,
    actualizado_en  TIMESTAMP     NOT NULL,
    aceptado_en     TIMESTAMP,
    entregado_en    TIMESTAMP,     -- con creado_en permite calcular el lead time
    CONSTRAINT ck_pedidos_estado CHECK (estado IN
        ('CREADO', 'ACEPTADO', 'EN_PREPARACION', 'DESPACHADO', 'ENTREGADO', 'CANCELADO'))
);
CREATE INDEX ix_pedidos_estado ON pedidos (estado);
CREATE INDEX ix_pedidos_email  ON pedidos (cliente_email);

-- Nombre y precio se copian del catálogo al crear el pedido: si después cambia el
-- precio del producto, el pedido mantiene el precio con el que se compró.
CREATE TABLE pedido_items (
    id               NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        NUMBER(19)    NOT NULL,
    producto_id      NUMBER(19)    NOT NULL,
    nombre           VARCHAR2(120) NOT NULL,
    precio_unitario  NUMBER(12)    NOT NULL,
    cantidad         NUMBER(10)    NOT NULL,
    CONSTRAINT fk_items_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE,
    CONSTRAINT ck_items_cantidad CHECK (cantidad > 0)
);
CREATE INDEX ix_items_pedido ON pedido_items (pedido_id);

-- Historial de cambios de estado (quién no se registra aún: llega con Entra ID en la Etapa 6)
CREATE TABLE pedido_historial (
    id               NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        NUMBER(19)   NOT NULL,
    estado_anterior  VARCHAR2(20),
    estado_nuevo     VARCHAR2(20) NOT NULL,
    cambiado_en      TIMESTAMP    NOT NULL,
    CONSTRAINT fk_historial_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE
);
CREATE INDEX ix_historial_pedido ON pedido_historial (pedido_id);
