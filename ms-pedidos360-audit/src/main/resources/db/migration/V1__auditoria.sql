-- Auditoría: un registro por evento recibido desde Kafka (solo inserción).
CREATE TABLE audit_evento (
    id            NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      VARCHAR2(36)   NOT NULL,
    topico        VARCHAR2(100)  NOT NULL,
    particion     NUMBER(5)      NOT NULL,
    offset_kafka  NUMBER(19)     NOT NULL,
    tipo          VARCHAR2(50)   NOT NULL,
    entidad       VARCHAR2(20)   NOT NULL,
    entidad_id    NUMBER(19),
    pedido_id     NUMBER(19),
    descripcion   VARCHAR2(500),
    usuario       VARCHAR2(200),
    payload       CLOB           NOT NULL,
    ocurrido_en   TIMESTAMP      NOT NULL,
    recibido_en   TIMESTAMP      NOT NULL,
    -- Idempotencia: el mismo evento entregado dos veces no crea dos filas
    CONSTRAINT uk_audit_event_id UNIQUE (event_id)
);

CREATE INDEX ix_audit_entidad  ON audit_evento (entidad, entidad_id);
CREATE INDEX ix_audit_pedido   ON audit_evento (pedido_id);
CREATE INDEX ix_audit_ocurrido ON audit_evento (ocurrido_en);
